/**
 * Рубли из ответа площадки (число с плавающей точкой) в целые копейки.
 * Точно работает только для значений не более чем с двумя знаками после запятой —
 * ровно то, что отдают API площадок. Число с тремя и более знаками уже потеряло
 * точность в double до вызова этой функции, и корректно округлить его здесь
 * невозможно: rubToMinor(1.005) → 100, rubToMinor(8.165) → 816, потому что
 * 1.005 и 8.165 не представимы в double точно — это не баг округления здесь.
 */
export function rubToMinor(rub: number): number {
  if (!Number.isFinite(rub)) throw new RangeError(`не число: ${rub}`)
  return Math.round(rub * 100)
}

/**
 * Десятичная строка в целые копейки, без промежуточного числа с плавающей
 * точкой. Нужна там, где площадка отдаёт деньги строкой: новая финансовая
 * детализация Wildberries и цена в заказе Ozon.
 *
 * Почему не `rubToMinor(Number(s))`: тот округляет, а нам нужно усечение.
 * `Math.round(Number("12.345") * 100)` даёт 1235 — на копейку больше, чем
 * записано в строке. На двух знаках после точки, которые обычно и присылает
 * площадка, оба способа сходятся; расходятся они на третьем знаке, и там
 * сторона расхождения зависит от того, куда легло значение в двоичной дроби.
 * Разбор по строке не проходит через двоичную дробь вовсе, поэтому усечение
 * у него — свойство реализации, а не совпадение.
 *
 * Разряды мельче копейки отбрасываются, а не округляются: в копейке нет
 * долей, а округление вверх на тысячах строк создаёт расхождение из ничего.
 */
export function decimalStringToMinor(value: string): number {
  const trimmed = value.trim()
  if (trimmed === "") return 0
  if (!/^-?\d+(\.\d+)?$/.test(trimmed)) {
    throw new RangeError(`не десятичная строка: ${value}`)
  }
  const negative = trimmed.startsWith("-")
  const [whole = "0", fraction = ""] = trimmed.replace(/^-/, "").split(".")
  const kopecks = `${fraction}00`.slice(0, 2)
  const minor = Number(whole) * 100 + Number(kopecks)
  return negative ? -minor : minor
}
